// Doubao (豆包) credential layer.
//
// Doubao's desktop app is Chromium-based, so its session lives in the standard
// Windows cookie store. The credential is recoverable WITHOUT running the app:
//
//	User Data\Local State → os_crypt.encrypted_key (base64, "DPAPI" prefix)
//	  → CryptUnprotectData(CurrentUser) → 32-byte AES master key
//	User Data\Default\Network\Cookies → encrypted_value = "v10" | nonce(12) |
//	  ciphertext | tag(16)  → AES-256-GCM(master, nonce, ct||tag)
//	  → plaintext, whose first 32 bytes are a fixed header (real value follows)
//
// This yields sessionid / ttwid / passport_csrf_token and friends, enough to
// know WHICH account is signed in. It does NOT solve the request-signing layer
// (a_bogus / X-Bogus / msToken, generated by obfuscated JS), so chat cannot be
// proxied safely — see source_doubao.go.

package main

import (
	"crypto/aes"
	"crypto/cipher"
	"encoding/base64"
	"encoding/json"
	"fmt"
	"os"
	"path/filepath"
	"runtime"
	"strings"
)

// doubaoCookieNames are the session cookies that identify a signed-in account.
var doubaoCookieNames = []string{
	"sessionid", "sessionid_ss", "sid_guard", "sid_tt", "uid_tt",
	"ttwid", "passport_csrf_token", "odin_tt", "multi_sids",
}

// doubaoUserDataDir locates the Chromium user-data directory.
func doubaoUserDataDir() string {
	if runtime.GOOS != "windows" {
		return ""
	}
	local := os.Getenv("LOCALAPPDATA")
	if local == "" {
		return ""
	}
	return filepath.Join(local, "Doubao", "User Data")
}

// envDoubaoAppPath lets a user point at a non-standard install, mirroring the
// WorkBuddy source's WORKBUDDY_ELECTRON_BIN convention.
const envDoubaoAppPath = "DOUBAO_APP_PATH"

// doubaoAppPath detects the installed desktop app.
func doubaoAppPath() string {
	if runtime.GOOS != "windows" {
		return ""
	}
	// An explicit path is authoritative and never falls back.
	if explicit := os.Getenv(envDoubaoAppPath); explicit != "" {
		if _, err := os.Stat(explicit); err == nil {
			return explicit
		}
	}
	// Standard install locations, in probe order.
	var candidates []string
	if local := os.Getenv("LOCALAPPDATA"); local != "" {
		candidates = append(candidates,
			filepath.Join(local, "Programs", "Doubao", "Doubao.exe"),
			filepath.Join(local, "Doubao", "Doubao.exe"))
	}
	if pf := os.Getenv("ProgramFiles"); pf != "" {
		candidates = append(candidates, filepath.Join(pf, "Doubao", "Doubao.exe"))
	}
	for _, candidate := range candidates {
		if _, err := os.Stat(candidate); err == nil {
			return candidate
		}
	}
	return ""
}

// doubaoCookieDB finds the cookie database (post-2020 layout first).
func doubaoCookieDB(userData string) string {
	for _, profile := range []string{"Default", "Profile 1"} {
		candidates := []string{
			filepath.Join(userData, profile, "Network", "Cookies"),
			filepath.Join(userData, profile, "Cookies"),
		}
		for _, candidate := range candidates {
			if _, err := os.Stat(candidate); err == nil {
				return candidate
			}
		}
	}
	return ""
}

// doubaoMasterKey reads and DPAPI-unwraps the os_crypt AES master key.
func doubaoMasterKey(userData string) ([]byte, error) {
	raw, err := os.ReadFile(filepath.Join(userData, "Local State"))
	if err != nil {
		return nil, fmt.Errorf("cannot read Local State: %w", err)
	}
	var doc struct {
		OSCrypt struct {
			EncryptedKey string `json:"encrypted_key"`
		} `json:"os_crypt"`
	}
	if err := json.Unmarshal(raw, &doc); err != nil {
		return nil, fmt.Errorf("Local State is not readable: %w", err)
	}
	if doc.OSCrypt.EncryptedKey == "" {
		return nil, fmt.Errorf("Local State carries no os_crypt.encrypted_key")
	}
	blob, err := base64.StdEncoding.DecodeString(doc.OSCrypt.EncryptedKey)
	if err != nil {
		return nil, fmt.Errorf("encrypted_key is not base64: %w", err)
	}
	// The blob is prefixed with the ASCII bytes "DPAPI".
	if len(blob) < 5 || string(blob[:5]) != "DPAPI" {
		return nil, fmt.Errorf("encrypted_key has no DPAPI prefix")
	}
	key, err := dpapiUnprotect(blob[5:])
	if err != nil {
		return nil, err
	}
	if len(key) != 32 {
		return nil, fmt.Errorf("unwrapped master key is %d bytes, want 32", len(key))
	}
	return key, nil
}

// doubaoDecryptCookieValue decrypts one v10 encrypted_value blob.
func doubaoDecryptCookieValue(key, blob []byte) (string, error) {
	if len(blob) < 3 || string(blob[:3]) != "v10" {
		return "", fmt.Errorf("cookie value is not v10-framed")
	}
	payload := blob[3:]
	// v10 layout: nonce(12) | ciphertext | tag(16).
	if len(payload) < 12+16 {
		return "", fmt.Errorf("cookie value too short")
	}
	nonce := payload[:12]
	ctAndTag := payload[12:]
	block, err := aes.NewCipher(key)
	if err != nil {
		return "", err
	}
	gcm, err := cipher.NewGCM(block)
	if err != nil {
		return "", err
	}
	plain, err := gcm.Open(nil, nonce, ctAndTag, nil)
	if err != nil {
		return "", fmt.Errorf("cookie decrypt failed (bad key or corrupt value): %w", err)
	}
	// The first 32 bytes are a fixed two-part header; the real value follows.
	if len(plain) > 32 {
		plain = plain[32:]
	}
	return string(plain), nil
}

// doubaoSession is the decrypted cookie set for the signed-in account.
type doubaoSession struct {
	Cookies map[string]string
	UID     string
}

// readDoubaoSession decrypts the Doubao cookie store.
func readDoubaoSession() (*doubaoSession, string, error) {
	userData := doubaoUserDataDir()
	if userData == "" {
		return nil, "", fmt.Errorf("Doubao user-data location is unknown on this platform")
	}
	if _, err := os.Stat(userData); err != nil {
		return nil, "", fmt.Errorf("Doubao is not installed (%s not found)", userData)
	}
	cookieDB := doubaoCookieDB(userData)
	if cookieDB == "" {
		return nil, userData, fmt.Errorf("no cookie database found under %s", userData)
	}
	key, err := doubaoMasterKey(userData)
	if err != nil {
		return nil, cookieDB, err
	}
	rows, err := querySQLite(cookieDB,
		`select name, encrypted_value from cookies where host_key like '%doubao.com%' or host_key like '%bytedance%'`)
	if err != nil {
		// Chromium cookie stores are WAL-mode; retry with an immutable read in
		// case a stale -wal blocks the plain open.
		rows, err = querySQLiteImmutable(cookieDB,
			`select name, encrypted_value from cookies where host_key like '%doubao.com%' or host_key like '%bytedance%'`)
	}
	if err != nil {
		return nil, cookieDB, fmt.Errorf("cannot read cookie database (若豆包正在运行,它会独占锁定该文件——请先完全退出豆包再试): %w", err)
	}
	session := &doubaoSession{Cookies: map[string]string{}}
	for _, row := range rows {
		if len(row) < 2 {
			continue
		}
		name := row[0]
		if !doubaoCookieWanted(name) {
			continue
		}
		value, err := doubaoDecryptCookieValue(key, []byte(row[1]))
		if err != nil || value == "" {
			continue
		}
		session.Cookies[name] = value
	}
	if _, ok := session.Cookies["sessionid"]; ok {
		session.UID = session.Cookies["uid_tt"]
	}
	if len(session.Cookies) == 0 {
		return nil, cookieDB, fmt.Errorf("no Doubao session cookies could be decrypted (not signed in?)")
	}
	return session, cookieDB, nil
}

func doubaoCookieWanted(name string) bool {
	for _, want := range doubaoCookieNames {
		if name == want {
			return true
		}
	}
	return false
}

// doubaoCookieHeader renders the session as a Cookie request header value.
func (s *doubaoSession) cookieHeader() string {
	parts := make([]string, 0, len(s.Cookies))
	for name, value := range s.Cookies {
		parts = append(parts, name+"="+value)
	}
	return strings.Join(parts, "; ")
}
